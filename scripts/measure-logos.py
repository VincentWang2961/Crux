#!/usr/bin/env python3
"""Measure the organisation logos in public/logos/ for optical sizing (org-logo.tsx).

For every logo (<key>.svg or <key>.png; <key>-dark.* is its dark-theme twin with the same
geometry) it renders the file, finds the ink (alpha > ALPHA_MIN), and records:
  - aspect:   ink width / ink height
  - coverage: how much of the ink's bounding box is actually inked (mean alpha, 0..1),
              e.g. a solid disc is about 0.79, an open wordmark about 0.35.
With --trim it also crops each file to its ink first: SVG viewBoxes are rewritten, PNGs are
cropped, so the sizing works on the mark itself and not on stray whitespace.

The numbers are written to src/lib/logo-metrics.ts; the sizing formula lives in org-logo.tsx.

Needs rsvg-convert (librsvg) and Pillow:
  brew install librsvg && python3 -m pip install pillow
  python3 scripts/measure-logos.py --trim
"""

import io
import json
import re
import subprocess
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
LOGOS = ROOT / "public" / "logos"
OUT = ROOT / "src" / "lib" / "logo-metrics.ts"
RENDER = 512  # px on the longer side
ALPHA_MIN = 8


def render(path: Path) -> Image.Image:
    if path.suffix == ".png":
        return Image.open(path).convert("RGBA")
    png = subprocess.run(
        ["rsvg-convert", "-w", str(RENDER), "--keep-aspect-ratio", str(path)],
        check=True,
        capture_output=True,
    ).stdout
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    if img.height > img.width:  # re-render so the longer side is RENDER
        png = subprocess.run(
            ["rsvg-convert", "-h", str(RENDER), "--keep-aspect-ratio", str(path)],
            check=True,
            capture_output=True,
        ).stdout
        img = Image.open(io.BytesIO(png)).convert("RGBA")
    return img


def ink_box(img: Image.Image):
    alpha = img.getchannel("A").point(lambda a: 255 if a > ALPHA_MIN else 0)
    return alpha.getbbox()


def trim_svg(path: Path, img: Image.Image, box) -> None:
    text = path.read_text()
    m = re.search(r'viewBox="([-\d.\s,]+)"', text)
    x, y, w, h = (float(v) for v in re.split(r"[\s,]+", m.group(1).strip()))
    sx, sy = w / img.width, h / img.height
    x0, y0, x1, y1 = box
    vb = f"{x + x0 * sx:.3f} {y + y0 * sy:.3f} {(x1 - x0) * sx:.3f} {(y1 - y0) * sy:.3f}"
    text = text.replace(m.group(0), f'viewBox="{vb}"', 1)
    text = re.sub(r'\s(width|height)="[^"]*"', "", text, count=2) if "<svg" in text[:200] else text
    path.write_text(text)


def main() -> None:
    trim = "--trim" in sys.argv
    files = sorted(p for p in LOGOS.iterdir() if p.suffix in {".svg", ".png"} and "-dark" not in p.stem)
    metrics = {}
    for path in files:
        img = render(path)
        box = ink_box(img)
        if trim and box != (0, 0, img.width, img.height):
            if path.suffix == ".svg":
                trim_svg(path, img, box)
                for dark in LOGOS.glob(f"{path.stem}-dark.svg"):
                    trim_svg(dark, img, box)
            else:
                Image.open(path).crop(box).save(path, optimize=True)
            img = render(path)
            box = ink_box(img)
        x0, y0, x1, y1 = box
        ink = img.crop(box).getchannel("A")
        coverage = sum(i * n for i, n in enumerate(ink.histogram())) / 255 / (ink.width * ink.height)
        dark = next((p.name for p in LOGOS.glob(f"{path.stem}-dark.*")), None)
        metrics[path.stem] = {
            "src": f"/logos/{path.name}",
            **({"darkSrc": f"/logos/{dark}"} if dark else {}),
            "aspect": round((x1 - x0) / (y1 - y0), 4),
            "coverage": round(coverage, 4),
        }
        print(f"{path.stem:12} aspect {metrics[path.stem]['aspect']:.3f}  coverage {coverage:.3f}")

    OUT.write_text(
        "// Generated by scripts/measure-logos.py from public/logos/. Do not edit by hand.\n"
        "// aspect = ink width / height; coverage = inked share of the ink's bounding box (0..1).\n\n"
        "export type LogoMetrics = { src: string; darkSrc?: string; aspect: number; coverage: number };\n\n"
        f"export const LOGO_METRICS = {json.dumps(metrics, indent=2)} satisfies Record<string, LogoMetrics>;\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
