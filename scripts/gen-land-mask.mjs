// Regenerates src/lib/land-mask.ts. Deps are NOT project deps; install them elsewhere:
//   mkdir /tmp/mg && cd /tmp/mg && npm init -y && npm i world-atlas@2 topojson-client@3
//   node scripts/gen-land-mask.mjs /tmp/mg src/lib/land-mask.ts
//
// Method: scanline-rasterise Natural Earth 1:50m land (per-ring even-odd, XOR-combined,
// antimeridian-safe) at STEP/SS
// resolution, then downsample SS×SS blocks: a cell is land if ≥ half its samples are.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const STEP = 0.5; // output cell size in degrees
const SS = 4; // supersampling factor per axis

const req = createRequire(process.argv[2] + "/package.json");
const { feature } = req("topojson-client");
const topo = req("world-atlas/land-50m.json");
const land = feature(topo, topo.objects.land);

const rings = [];
const geoms = land.features ? land.features.map((f) => f.geometry) : [land.geometry ?? land];
for (const g of geoms) {
  const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const ring of poly) rings.push(ring);
}

// Unwrap each ring's longitudes so edges never jump across the antimeridian
// (e.g. Chukotka spans 180°). A ring that wraps fully around the globe (net 360°
// shift, i.e. Antarctica) is closed through its pole so it becomes a simple polygon.
const unwrapped = rings.map((ring) => {
  const out = [[ring[0][0], ring[0][1]]];
  for (let i = 1; i < ring.length; i++) {
    let x = ring[i][0];
    const px = out[i - 1][0];
    while (x - px > 180) x -= 360;
    while (x - px < -180) x += 360;
    out.push([x, ring[i][1]]);
  }
  const shift = out[out.length - 1][0] - out[0][0];
  if (Math.abs(shift) > 180) {
    const meanLat = out.reduce((a, p) => a + p[1], 0) / out.length;
    const pole = meanLat < 0 ? -90 : 90;
    out.push([out[out.length - 1][0], pole], [out[0][0], pole]);
  }
  return out;
});

const ROWS = Math.round(180 / STEP), COLS = Math.round(360 / STEP);
const FR = ROWS * SS, FC = COLS * SS, fine = STEP / SS;
const hits = new Uint8Array(ROWS * COLS);
const diff = new Uint8Array(FC + 1);
// XOR-toggle fine columns whose centres lie in [a, b] (degrees, may exceed ±180).
const toggle = (a, b) => {
  const k = Math.floor((a + 180) / 360);
  a -= 360 * k;
  b -= 360 * k;
  if (b > 180) {
    toggle(a, 180);
    toggle(-180, b - 360);
    return;
  }
  const c0 = Math.max(0, Math.ceil((a + 180) / fine - 0.5));
  const c1 = Math.min(FC - 1, Math.floor((b + 180) / fine - 0.5));
  if (c0 <= c1) {
    diff[c0] ^= 1;
    diff[c1 + 1] ^= 1;
  }
};
for (let fr = 0; fr < FR; fr++) {
  const lat = 90 - (fr + 0.5) * fine;
  diff.fill(0);
  for (const ring of unwrapped) {
    const xs = [];
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [x1, y1] = ring[j], [x2, y2] = ring[i];
      if ((y1 <= lat) !== (y2 <= lat)) xs.push(x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1));
    }
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) toggle(xs[k], xs[k + 1]);
  }
  let inside = 0;
  for (let fc = 0; fc < FC; fc++) {
    inside ^= diff[fc];
    if (inside) hits[((fr / SS) | 0) * COLS + ((fc / SS) | 0)]++;
  }
}

const bytes = new Uint8Array(Math.ceil((ROWS * COLS) / 8));
let count = 0;
for (let k = 0; k < ROWS * COLS; k++) {
  if (hits[k] * 2 >= SS * SS) { bytes[k >> 3] |= 1 << (k & 7); count++; }
}
const b64 = Buffer.from(bytes).toString("base64");
const lines = b64.match(/.{1,100}/g).map((l) => `  "${l}"`).join(" +\n");
writeFileSync(process.argv[3], `// AUTO-GENERATED by scripts/gen-land-mask.mjs — do not edit by hand.
// Land/ocean bitmap for the matrix globe. Source: Natural Earth 1:50m land (world-atlas@2).
// Grid: ${STEP}° cells, ${ROWS} rows (row 0 starts at 90°N) × ${COLS} cols (col 0 starts at 180°W).
// Bits are row-major, LSB-first, base64. ${count} land cells (${((100 * count) / (ROWS * COLS)).toFixed(1)}%).

export const LAND_GRID_STEP = ${STEP};
export const LAND_GRID_ROWS = ${ROWS};
export const LAND_GRID_COLS = ${COLS};

export const LAND_MASK_BASE64 =
${lines};
`);
console.log(`land cells ${count} of ${ROWS * COLS}`);
